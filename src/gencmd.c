void datestamp(void)
{
	char	str[100],*th;
	struct tm *t;
	time_t	now;

	time(&now);
	t = localtime(&now);

	switch(t->tm_mday)
	{
	case 31:
	case 21:
	case 1:th="st";break;
	case 22:
	case 2:th="nd";break;
	case 23:
	case 3:th="rd";break;
	default:th="th";
	}
	to_file(1,"\"%s %i%s, %i at %i:%02i%s\"",month[t->tm_mon],t->tm_mday,th,
		t->tm_year + 1900,hourampm[t->tm_hour],t->tm_min,(t->tm_hour <= 11) ? "am" : "pm");
}

