void test_help(void)
{
	char	tmp[PATH_MAX];
        struct stat st;
        int     i,r;

	for(i=0;pre_mcmd[i].name;i++)
	{
		sprintf(tmp,"../help/%s",pre_mcmd[i].name);
		r = stat(tmp,&st);

		if (r == -1 && errno == ENOENT)
			to_file(1,"help for %s is missing\n",pre_mcmd[i].name);
	}
	exit(0);
}

