int linecount;

int countcallback(char *line)
{
	linecount++;
	return(FALSE);
}

int countlines(const char *filename)
{
	int	fd;

	linecount = 0;
	if ((fd = open(filename,O_RDONLY)) < 0)
		return(0);
	readline(fd,&countcallback); /* readline closes fd */
	return(linecount);
}

